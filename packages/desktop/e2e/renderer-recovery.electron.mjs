import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { createServer } from "node:http";
import path from "node:path";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import { expect } from "playwright/test";
import { readDaemonInstance } from "@getpaseo/server/daemon-control";

// Native automation is restricted to the isolated Electron process from this test
const runFile = promisify(execFile);

/** Invoke a real Windows dialog button without sending input to other applications */
async function answerNativeDialog({ desktop, script, button }) {
  // Isolated Electron main-process PID used as the UI Automation boundary
  const pid = await desktop.evaluate(() => process.pid);
  // Native responder reports only the isolated PID and selected action
  const response = await runFile(
    "powershell.exe",
    ["-NoProfile", "-STA", "-File", script, "-ProcessId", String(pid), "-Button", button],
    { windowsHide: true, timeout: 25_000 },
  );
  console.log(response.stdout.trim());
}

/** Verify renderer replacement and native recovery against an isolated running daemon */
export async function verifyRendererRecovery({ desktop, root, home, instance }) {
  // Minimal document fixture isolates native recovery from agent-provider setup
  const server = createServer((_request, response) => {
    response.setHeader("Content-Type", "text/html");
    response.end(
      '<div id="root"><button data-testid="open-project-submit">Open project</button></div>',
    );
  });
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  // Local fixture origin has no production daemon ports or state
  const address = server.address();
  assert.ok(address && typeof address !== "string");
  // Recovery route exercises a real main-frame navigation
  const url = `http://127.0.0.1:${address.port}/open-project`;
  // PID-scoped native dialog responder stored in the suite's temporary directory
  const script = path.join(root, "answer-recovery-dialog.ps1");
  await writeFile(
    script,
    `param([int]$ProcessId, [string]$Button)
Add-Type -AssemblyName UIAutomationClient
Add-Type -AssemblyName UIAutomationTypes
Add-Type -TypeDefinition 'using System; using System.Runtime.InteropServices; public static class RecoveryButton { [DllImport("user32.dll")] public static extern bool PostMessage(IntPtr hwnd, uint msg, IntPtr wParam, IntPtr lParam); }'
$deadline = [DateTime]::UtcNow.AddSeconds(20)
$processCondition = [System.Windows.Automation.PropertyCondition]::new([System.Windows.Automation.AutomationElement]::ProcessIdProperty, $ProcessId)
$titleCondition = [System.Windows.Automation.PropertyCondition]::new([System.Windows.Automation.AutomationElement]::NameProperty, 'Recover Paseo window')
$dialogCondition = [System.Windows.Automation.AndCondition]::new($processCondition, $titleCondition)
$buttonCondition = [System.Windows.Automation.PropertyCondition]::new([System.Windows.Automation.AutomationElement]::NameProperty, $Button)
while ([DateTime]::UtcNow -lt $deadline) {
  $dialog = [System.Windows.Automation.AutomationElement]::RootElement.FindFirst([System.Windows.Automation.TreeScope]::Descendants, $dialogCondition)
  if ($null -ne $dialog) {
    $action = $dialog.FindFirst([System.Windows.Automation.TreeScope]::Descendants, $buttonCondition)
    if ($null -ne $action) {
      $handle = $action.Current.NativeWindowHandle
      if ($handle -eq 0) {
        $invoke = $action.GetCurrentPattern([System.Windows.Automation.InvokePattern]::Pattern)
        $invoke.Invoke()
      } else {
        if (-not [RecoveryButton]::PostMessage([IntPtr]$handle, 0x00F5, [IntPtr]::Zero, [IntPtr]::Zero)) { throw 'Failed to click isolated native button' }
      }
      Write-Output "Invoked $Button in isolated process $ProcessId"
      exit 0
    }
  }
  Start-Sleep -Milliseconds 100
}
$windows = [System.Windows.Automation.AutomationElement]::RootElement.FindAll([System.Windows.Automation.TreeScope]::Descendants, $processCondition)
$names = @($windows | ForEach-Object { $_.Current.Name }) -join ' | '
throw "Native recovery dialog/button not found in isolated process $ProcessId; isolated UI: $names"
`,
  );
  try {
    await desktop.evaluate(
      async ({ BrowserWindow, app, Menu, nativeImage }, input) => {
        // Production adapter used unchanged inside the isolated fixture
        const { setupRendererRecovery } = global.rendererRecovery;
        // Native menu callbacks generated by the production tray module
        const { buildRecoveryTrayMenu, setupRecoveryTray } = global.recoveryTray;
        // Explicitly retain both native windows to test recovery isolation
        global.recoveryWindows = [];
        // Per-window controllers and native menu actions retained by this fixture
        global.recoveryControllers = [];
        // Lifecycle event counters must stay at zero throughout recovery
        global.recoveryClosed = 0;
        global.recoveryQuit = 0;
        // Real Windows tray uses the application's existing icon
        global.nativeRecoveryTray = setupRecoveryTray({
          icon: nativeImage.createFromPath(input.icon),
          windows: () =>
            global.recoveryWindows
              .filter((win) => !win.isDestroyed())
              .map((win, index) => ({
                id: win.id,
                recovering: global.recoveryControllers[index].isRecovering(),
                recover: () => void global.recoveryControllers[index].recover(),
              })),
          openLogs: () => {},
        });
        // Application object remains alive even with a dead renderer
        app.on("window-all-closed", () => global.recoveryClosed++);
        app.on("before-quit", () => global.recoveryQuit++);
        for (let index = 0; index < 2; index++) {
          // Renderer-painted window controls disappear when this process crashes
          const win = new BrowserWindow({ frame: false, show: true, width: 450, height: 250 });
          // Same native adapter attached to each independent window
          const recovery = setupRendererRecovery({
            win,
            recoveryUrl: input.url,
            beforeReset: () => {},
            changed: () => global.nativeRecoveryTray.refresh(),
          });
          global.recoveryWindows.push(win);
          global.recoveryControllers.push(recovery);
          await win.loadURL(input.url);
          global.nativeRecoveryTray.refresh();
        }
        global.recoveryMenu = Menu.buildFromTemplate(
          buildRecoveryTrayMenu(
            global.recoveryWindows.map((win, index) => ({
              id: win.id,
              recovering: false,
              recover: () => void global.recoveryControllers[index].recover(),
            })),
            () => {},
          ),
        );
      },
      {
        url,
        icon: fileURLToPath(new URL("../assets/icon.ico", import.meta.url)),
      },
    );
    // Identity of both native windows and original renderer processes
    const original = await desktop.evaluate(() =>
      global.recoveryWindows.map((win) => ({
        id: win.id,
        contentsId: win.webContents.id,
        pid: win.webContents.getOSProcessId(),
      })),
    );
    await desktop.evaluate(() => global.recoveryWindows[0].webContents.forcefullyCrashRenderer());
    await answerNativeDialog({ desktop, script, button: "Recover window" });
    await expect
      .poll(
        () =>
          desktop.evaluate(() => ({
            recovering: global.recoveryControllers[0].isRecovering(),
            crashed: global.recoveryWindows[0].webContents.isCrashed(),
          })),
        {
          timeout: 20_000,
        },
      )
      .toEqual({ recovering: false, crashed: false });
    // Native window is reused while only its renderer changes
    const recovered = await desktop.evaluate(() =>
      global.recoveryWindows.map((win) => ({
        id: win.id,
        contentsId: win.webContents.id,
        pid: win.webContents.getOSProcessId(),
        crashed: win.webContents.isCrashed(),
      })),
    );
    assert.equal(recovered[0].id, original[0].id);
    assert.equal(recovered[0].contentsId, original[0].contentsId);
    assert.notEqual(recovered[0].pid, original[0].pid);
    assert.equal(recovered[0].crashed, false);
    assert.equal(recovered[1].pid, original[1].pid);

    // Manual native menu action recovers a blank but responsive renderer five times
    for (let round = 0; round < 5; round++) {
      await desktop.evaluate(async () => {
        await global.recoveryWindows[0].webContents.executeJavaScript(
          "document.body.replaceChildren()",
        );
        global.recoveryMenu.items[0].submenu.items[0].click();
      });
      await expect
        .poll(() => desktop.evaluate(() => global.recoveryControllers[0].isRecovering()), {
          timeout: 20_000,
        })
        .toBe(false);
      assert.equal(
        await desktop.evaluate(() =>
          global.recoveryWindows[0].webContents.executeJavaScript(
            'Boolean(document.querySelector("[data-testid=open-project-submit]"))',
          ),
        ),
        true,
      );
    }
    // One remaining window exercises the Windows last-window exit boundary
    await desktop.evaluate(() => global.recoveryWindows[1].destroy());
    // Hang Chromium itself rather than synthesizing an unresponsive event
    await desktop.evaluate(async () => {
      void global.recoveryWindows[0].webContents
        .executeJavaScript("while (true) {}")
        .catch(() => {});
      await new Promise((resolve) => setTimeout(resolve, 100));
      // Tray recovery must also work when Chromium emits no unresponsive event
      global.recoveryMenu.items[0].submenu.items[0].click();
    });
    await expect
      .poll(
        () =>
          desktop.evaluate(() => ({
            recovering: global.recoveryControllers[0].isRecovering(),
            crashed: global.recoveryWindows[0].webContents.isCrashed(),
          })),
        {
          timeout: 20_000,
        },
      )
      .toEqual({ recovering: false, crashed: false });
    assert.deepEqual(
      await desktop.evaluate(() => ({ closed: global.recoveryClosed, quit: global.recoveryQuit })),
      { closed: 0, quit: 0 },
    );
    // Daemon lifetime remains independent of all renderer replacement attempts
    const after = await readDaemonInstance(home);
    assert.equal(after.pid, instance.pid);
    assert.equal(after.startedAt, instance.startedAt);
    process.kill(instance.pid, 0);
    console.log(
      "PASS: native crash recovery, blank/hung-window menu recovery, repeated resets, window isolation and daemon continuity",
    );
  } finally {
    await desktop.evaluate(() => {
      global.nativeRecoveryTray?.dispose();
      for (const win of global.recoveryWindows ?? []) if (!win.isDestroyed()) win.destroy();
    });
    await new Promise((resolve) => server.close(resolve));
  }
}
